"""Copy the TakeoffMetric constants CSV (dataset version 1.2.0) into data/ and regenerate
Sources/TakeoffMetric/ConstantsCSV.swift, which embeds the same bytes as a Swift string literal.

Usage: python sync_data.py [source.csv]
Default source: ../TakeoffMetrics-go/data/constants.csv (the table embedded by the Go module)
Only the header with the values_withheld and withheld_hosts columns (introduced in 1.1.0, unchanged in 1.2.0) is accepted.
Then run: swift test
"""
import csv
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
DEFAULT = HERE.parent / "TakeoffMetrics-go" / "data" / "constants.csv"
HEADER = ("id,category,material_or_item,quantity,value,unit,value_si,unit_si,condition,source_publisher,"
          "source_title,source_url,source_type,date_opened,used_by_tool_url,engine_file,engine_symbol,notes,"
          "values_withheld,withheld_hosts")

src = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT
raw = src.read_bytes()
text = raw.decode("utf-8")
rows = list(csv.reader(text.splitlines(keepends=True)))
if ",".join(rows[0]) != HEADER:
    sys.exit(f"unexpected header in {src}: {rows[0]}")
# The Swift literal is #"""...."""#: it must not contain the closing delimiter or a raw escape,
# and Swift turns every line break of a multi-line literal into LF.
if '"#' in text or "\\#" in text or "\r" in text:
    sys.exit(f"{src} contains \"#, \\# or CR: it cannot be embedded verbatim")
if not text.endswith("\n"):
    sys.exit(f"{src} does not end with a line feed")

(HERE / "data" / "constants.csv").write_bytes(raw)
swift = (
    "// Generated by sync_data.py from data/constants.csv. Do not edit.\n"
    "\n"
    "/// The constants table, byte for byte as data/constants.csv (UTF-8, LF line endings).\n"
    "let constantsCSV = #\"\"\"\n"
    + text
    + "\n\"\"\"#\n"
)
(HERE / "Sources" / "TakeoffMetric" / "ConstantsCSV.swift").write_bytes(swift.encode("utf-8"))
print(f"synced {len(rows) - 1} rows from {src}")
